# String Function

birth = "i am born in pakistan"
print(birth.endswith("an")) # check if string ends with "an"

print(birth.startswith("i")) # check if string starts with "i"

print(birth.find("born")) # find the index of the substring "born"

print(birth.count("a")) # count the occurrences of the character "a"

print(birth.replace("i am ", "i was "))
